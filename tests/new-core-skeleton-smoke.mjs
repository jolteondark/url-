import assert from 'node:assert/strict';
import { createInitialGameState, assertSerializableGameState } from '../src-next/core/game-state.js';
import { step } from '../src-next/core/step.js';

const initial = createInitialGameState({ runId: 'fixture', seed: 108, party: [{ id: 'p1', species: 'PIKACHU', level: 10, hp: 20, exp: 0 }] });
assert.deepEqual(assertSerializableGameState(initial), initial);
const slots = Array.from({ length: 8 }, (_, i) => ({ kind: i === 3 ? 'wild' : 'event', id: `slot-${i}`, encounter: i === 3 ? { species: 'TEST_FOE', level: 10, baseExp: 70 } : undefined }));
const board = step(initial, { type: 'BOARD_GENERATED', slots });
const selected = step(board.state, { type: 'BOARD_SELECT', slot: 3 });
const battleId = selected.state.activeBattle.id;
const terminal = step(selected.state, { type: 'BATTLE_TERMINAL_RESULT', battleId, resultId: 'result-1', outcome: 'win' });
assert.equal(terminal.state.board[3].consumed, true);
assert.equal(terminal.state.boardSelectionsRemaining, 7);
assert.equal(terminal.state.mode, 'battle_result');
assert.equal(terminal.events.at(-1).type, 'BATTLE_REWARD_REQUESTED');
assert.deepEqual(terminal.effects, []);
const rewardId = terminal.state.pendingBattleResult.rewardId;
const rewarded = step(terminal.state, { type: 'BATTLE_REWARD_RESULT', rewardId, recipientIds: ['p1'] });
assert.equal(rewarded.state.mode, 'board');
assert.equal(rewarded.state.money, 0);
assert.equal(rewarded.state.party[0].exp, 50);
assert.equal(rewarded.state.bag.items.POTION, 1);
assert.ok(rewarded.events.some((event) => event.type === 'ITEM_REWARDED' && event.itemId === 'POTION'));
assert.deepEqual(rewarded.effects, [{ type: 'REQUEST_SAVE', reason: 'battle_reward_result' }]);
const replayReward = step(rewarded.state, { type: 'BATTLE_REWARD_RESULT', rewardId, recipientIds: ['p1'] });
assert.equal(replayReward.state.money, 0);
assert.equal(replayReward.state.party[0].exp, 50);
assert.equal(replayReward.state.bag.items.POTION, 1);
assert.equal(replayReward.effects.length, 0);
const replayState = structuredClone(terminal.state);
replayState.activeBattle = { id: battleId, status: 'terminal', resultCommitted: false };
const replay = step(replayState, { type: 'BATTLE_TERMINAL_RESULT', battleId, resultId: 'result-1', outcome: 'win' });
assert.equal(replay.state.boardSelectionsRemaining, 7, 'terminal replay must not double-consume');
assert.equal(replay.effects.length, 0, 'terminal replay must not request another save');
console.log('new-core-skeleton-smoke: ok');
