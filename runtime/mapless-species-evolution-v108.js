function normalizeGender(gender) {
  if (gender === 0 || gender === "male" || gender === "MALE" || gender === "Male") return "male";
  if (gender === 1 || gender === "female" || gender === "FEMALE" || gender === "Female") return "female";
  return null;
}

export function canonicalEvolutionChoicesV108(pokemon) {
  if (!pokemon || typeof pokemon !== "object" || pokemon.egg === true || (pokemon.steps_to_hatch ?? 0) > 0) return [];
  const species = String(pokemon.species ?? "");
  if (!species) return [];
  const gender = normalizeGender(pokemon.gender);
  const rows = EVOLUTION_CHOICES_V108[species] ?? [];
  const choices = [];
  for (const row of rows) {
    if (row.gender && row.gender !== gender) continue;
    if (!choices.includes(row.species)) choices.push(row.species);
  }
  return choices;
}

export function canonicalEvolutionLabCandidatesV108(party) {
  if (!Array.isArray(party)) return [];
  return party
    .map((pokemon, index) => ({ index, pokemon, evolutions:canonicalEvolutionChoicesV108(pokemon) }))
    .filter((entry) => entry.evolutions.length > 0);
}

